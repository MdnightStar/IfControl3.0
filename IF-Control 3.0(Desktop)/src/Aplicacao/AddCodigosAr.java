    private void jButtonCompletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonCompletarActionPerformed
       if (verListaCod.size() == 0) {
            int resposta = JOptionPane.showConfirmDialog(
                    null, // Componente pai (null para centrar na tela)
                    "Nem um cod ir adicionado; Deseja procesguir?", // A mensagem a ser exibida
                    "Deseja?", // O título da janela
                    JOptionPane.YES_NO_OPTION, // As opções de botões (Sim e Não)
                    JOptionPane.QUESTION_MESSAGE // O ícone da caixa de diálogo

            );
            if (resposta == JOptionPane.YES_OPTION) {
                terminar();
            }
        }else if(verListaCod.size()<32){
            int resposta = JOptionPane.showConfirmDialog(
                    null, // Componente pai (null para centrar na tela)
                    "Falta mais codigos; Deseja procesguir?", // A mensagem a ser exibida
                    "Deseja?", // O título da janela
                    JOptionPane.YES_NO_OPTION, // As opções de botões (Sim e Não)
                    JOptionPane.QUESTION_MESSAGE // O ícone da caixa de diálogo

            );
            if (resposta == JOptionPane.YES_OPTION) {
                terminar();
            }
        }else{
            JOptionPane.showMessageDialog(null, "Codigos adicionados com sucesso", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            terminar();
        }
    }//GEN-LAST:event_jButtonCompletarActionPerformed

    private void jButtonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddActionPerformed
        // TODO add your handling code here:
        String modo=(String) comboBoxModo.getSelectedItem();
        String funcao;
        if(modo.contains("ON")||modo.contains("OFF")||modo.contains("Auto")||modo.contains("Fan")){
            funcao=modo;
        }else{
            funcao = (String) modo + comboBoxTemperatura.getSelectedItem();
        }
       
        String cod = jTextFieldCod.getText();
        if (verListaCod.containsKey(funcao)) {
            int resposta = JOptionPane.showConfirmDialog(
                    null, // Componente pai (null para centrar na tela)
                    "Deseja modificar o cod ir da funcao " + funcao, // A mensagem a ser exibida
                    "Deseja?", // O título da janela
                    JOptionPane.YES_NO_OPTION, // As opções de botões (Sim e Não)
                    JOptionPane.QUESTION_MESSAGE // O ícone da caixa de diálogo
            );
            if (resposta == JOptionPane.YES_OPTION) {
                verListaCod.put(funcao, cod);
                JOptionPane.showMessageDialog(null, "Editado: "+funcao, "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            }
        } else {
            verListaCod.put(funcao, cod);
            JOptionPane.showMessageDialog(null, "Adicionado: "+funcao, "Sucesso", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButtonAddActionPerformed

