    public AddCodigosAr(List<CodIr> codigos) {
        initComponents();
        setDefaultCloseOperation(JFrame.DISPOSE_ON_CLOSE);
        ListaCod = new ArrayList<>();
        
        verListaCod = new HashMap<>();
        for(CodIr cod:codigos){
            verListaCod.put(cod.getFuncao(), cod.getCod());
        }
    }

    public List<CodIr> getListaCod() {
        return ListaCod;
    }

    public boolean isCompletou() {
        return completou;
    }
    
    public void terminar() {
        for (Map.Entry<String, String> entry : verListaCod.entrySet()) {
            CodIr cod=new CodIr();
            cod.setFuncao(entry.getKey());
            cod.setCod(entry.getValue());
            ListaCod.add(cod);
        }
        completou=true;
        setVisible(false);
    }

